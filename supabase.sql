-- 已成为好友后，双方可只读查看彼此的“看完”记录及收藏夹。
drop policy if exists "Friends can read completed anime" on public.user_anime;
create policy "Friends can read completed anime" on public.user_anime for select using (
  status = 'done' and exists (
    select 1 from public.friendships f where f.status = 'accepted' and
    ((f.requester_id = auth.uid() and f.addressee_id = user_id) or
     (f.addressee_id = auth.uid() and f.requester_id = user_id))
  )
);
drop policy if exists "Friends can read collections" on public.anime_collections;
create policy "Friends can read collections" on public.anime_collections for select using (
  exists (
    select 1 from public.friendships f where f.status = 'accepted' and
    ((f.requester_id = auth.uid() and f.addressee_id = user_id) or
     (f.addressee_id = auth.uid() and f.requester_id = user_id))
  )
);

drop policy if exists "Authenticated users can read profiles" on public.profiles;
create policy "Authenticated users can read profiles" on public.profiles for select to authenticated using (
  id = auth.uid() or exists (
    select 1 from public.friendships f where
    (f.requester_id = auth.uid() and f.addressee_id = profiles.id) or
    (f.addressee_id = auth.uid() and f.requester_id = profiles.id)
  )
);
drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Users can read related friendships" on public.friendships;
