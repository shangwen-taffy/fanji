create policy "Users can create friend requests" on public.friendships for insert with check (auth.uid() = requester_id and status = 'pending');
create policy "Addressee can update friend requests" on public.friendships for update using (auth.uid() = addressee_id) with check (auth.uid() = addressee_id);
create policy "Users can delete related friendships" on public.friendships for delete using (auth.uid() in (requester_id, addressee_id));

create or replace function public.handle_new_user_profile()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id,email,display_name,avatar_url)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'display_name',split_part(new.email,'@',1)),new.raw_user_meta_data->>'avatar_url')
  on conflict(id) do update set email=excluded.email, display_name=coalesce(excluded.display_name,profiles.display_name), avatar_url=coalesce(excluded.avatar_url,profiles.avatar_url), updated_at=now();
  return new;
end; $$;
drop trigger if exists on_auth_user_profile_changed on auth.users;
create trigger on_auth_user_profile_changed after insert or update of email,raw_user_meta_data on auth.users
for each row execute function public.handle_new_user_profile();

