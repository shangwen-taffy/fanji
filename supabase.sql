-- 尚文番迹数据库初始化 / 升级脚本（可重复运行）
create table if not exists public.anime_collections (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 30),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, name)
);

-- 好友功能：公开资料只用于好友界面；邮箱查找通过受控函数完成。
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  display_name text,
  avatar_url text,
  updated_at timestamptz not null default now()
);

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  addressee_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (requester_id <> addressee_id),
  unique(requester_id, addressee_id)
);

create table if not exists public.user_anime (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  anime_id bigint not null,
  name text not null,
  name_cn text,
  image_url text,
  total_episodes integer,
  community_score numeric(3,1),
  status text not null check (status in ('wish','watching','done','paused','dropped')) default 'wish',
  progress integer not null default 0 check (progress >= 0),
  rating integer not null default 0 check (rating between 0 and 10),
  note text,
  collection_id bigint references public.anime_collections(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, anime_id)
);

-- 为已经存在的旧表补上收藏夹字段。
alter table public.user_anime
  add column if not exists collection_id bigint references public.anime_collections(id) on delete set null;

